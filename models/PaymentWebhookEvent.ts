
import mongoose, { Document, Schema, Types } from "mongoose";

export type WebhookEventStatus =
  | "received"
  | "processing"
  | "processed"
  | "failed";

export interface IPaymobWebhookEvent extends Document {
  eventKey: string;

  eventType: string;

  status: WebhookEventStatus;

  paymentId: Types.ObjectId | null;
  enrollmentId: Types.ObjectId | null;

  paymobTransactionId?: string;
  paymobOrderId?: string;
  paymobSubscriptionId?: string;

  payloadHash: string;

  attempts: number;

  receivedAt: Date;
  processedAt: Date | null;

  lastError?: string;

  createdAt: Date;
  updatedAt: Date;
}

const PaymobWebhookEventSchema =
  new Schema<IPaymobWebhookEvent>(
    {
      // Deterministic key generated by our webhook handler.
      // Prevents duplicate processing of the same provider event.
      eventKey: {
        type: String,
        required: true,
        unique: true,
        trim: true,
      },

      eventType: {
        type: String,
        required: true,
        trim: true,
      },

      status: {
        type: String,
        enum: [
          "received",
          "processing",
          "processed",
          "failed",
        ],
        default: "received",
        required: true,
      },

      paymentId: {
        type: Schema.Types.ObjectId,
        ref: "Payment",
        default: null,
      },

      enrollmentId: {
        type: Schema.Types.ObjectId,
        ref: "Enrollment",
        default: null,
      },

      paymobTransactionId: {
        type: String,
        trim: true,
      },

      paymobOrderId: {
        type: String,
        trim: true,
      },

      paymobSubscriptionId: {
        type: String,
        trim: true,
      },

      // SHA-256 hash of the verified callback payload.
      // We do not store sensitive card information.
      payloadHash: {
        type: String,
        required: true,
      },

      attempts: {
        type: Number,
        default: 0,
        min: 0,
      },

      receivedAt: {
        type: Date,
        default: Date.now,
      },

      processedAt: {
        type: Date,
        default: null,
      },

      lastError: {
        type: String,
        maxlength: 1000,
      },
    },
    {
      timestamps: true,
    },
  );

PaymobWebhookEventSchema.index({
  status: 1,
  receivedAt: 1,
});

PaymobWebhookEventSchema.index({
  paymentId: 1,
});

PaymobWebhookEventSchema.index({
  enrollmentId: 1,
});

const PaymobWebhookEvent =
  mongoose.models.PaymobWebhookEvent ||
  mongoose.model<IPaymobWebhookEvent>(
    "PaymobWebhookEvent",
    PaymobWebhookEventSchema,
  );

export default PaymobWebhookEvent;
