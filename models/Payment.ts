
import mongoose, { Document, Schema, Types } from "mongoose";

export type PaymentStatus =
  | "pending"
  | "successful"
  | "failed"
  | "cancelled"
  | "expired"
  | "refunded";

export type PaymentMethod = "card" | "wallet";

export type PaymentBillingType = "recurring" | "manual";

export type PaymentKind = "initial" | "renewal";

export interface IPayment extends Document {
  userId: Types.ObjectId;
  courseId: Types.ObjectId;
  enrollmentId: Types.ObjectId;

  kind: PaymentKind;
  billingType: PaymentBillingType;
  paymentMethod: PaymentMethod;

  provider: "paymob";

  amountMinor: number;
  currency: string;

  status: PaymentStatus;

  checkoutReference: string;
  idempotencyKey: string;

  paymobIntentionId?: string;
  paymobOrderId?: string;
  paymobTransactionId?: string;
  paymobSubscriptionId?: string;

  billingPeriodStart: Date | null;
  billingPeriodEnd: Date | null;

  paidAt: Date | null;
  failedAt: Date | null;
  expiresAt: Date | null;

  failureCode?: string;
  failureMessage?: string;

  createdAt: Date;
  updatedAt: Date;
}

const PaymentSchema = new Schema<IPayment>(
  {
    userId: {
      type: Schema.Types.ObjectId,
      ref: "User",
      required: true,
    },

    courseId: {
      type: Schema.Types.ObjectId,
      ref: "Course",
      required: true,
    },

    enrollmentId: {
      type: Schema.Types.ObjectId,
      ref: "Enrollment",
      required: true,
    },

    kind: {
      type: String,
      enum: ["initial", "renewal"],
      required: true,
    },

    billingType: {
      type: String,
      enum: ["recurring", "manual"],
      required: true,
    },

    paymentMethod: {
      type: String,
      enum: ["card", "wallet"],
      required: true,
    },

    provider: {
      type: String,
      enum: ["paymob"],
      default: "paymob",
      required: true,
    },

    amountMinor: {
      type: Number,
      required: true,
      min: 1,
      validate: Number.isSafeInteger,
    },

    currency: {
      type: String,
      enum: ["EGP"],
      default: "EGP",
      required: true,
    },

    status: {
      type: String,
      enum: [
        "pending",
        "successful",
        "failed",
        "cancelled",
        "expired",
        "refunded",
      ],
      default: "pending",
      required: true,
    },

    // Generated by CrestInEnglish.
    checkoutReference: {
      type: String,
      required: true,
      unique: true,
      trim: true,
    },

    // Prevent creating duplicate checkout operations.
    idempotencyKey: {
      type: String,
      required: true,
      unique: true,
      trim: true,
    },

    paymobIntentionId: {
      type: String,
      trim: true,
    },

    paymobOrderId: {
      type: String,
      trim: true,
    },

    paymobTransactionId: {
      type: String,
      trim: true,
    },

    paymobSubscriptionId: {
      type: String,
      trim: true,
    },

    // The period this payment is intended to cover.
    billingPeriodStart: {
      type: Date,
      default: null,
    },

    billingPeriodEnd: {
      type: Date,
      default: null,
    },

    paidAt: {
      type: Date,
      default: null,
    },

    failedAt: {
      type: Date,
      default: null,
    },

    expiresAt: {
      type: Date,
      default: null,
    },

    failureCode: {
      type: String,
      trim: true,
    },

    failureMessage: {
      type: String,
      trim: true,
      maxlength: 500,
    },
  },
  {
    timestamps: true,
  },
);

// Avoid duplicate Paymob transaction processing.
PaymentSchema.index(
  { paymobTransactionId: 1 },
  {
    unique: true,
    partialFilterExpression: {
      paymobTransactionId: { $type: "string" },
    },
  },
);

PaymentSchema.index({
  enrollmentId: 1,
  createdAt: -1,
});

PaymentSchema.index({
  userId: 1,
  createdAt: -1,
});

PaymentSchema.index({
  paymobIntentionId: 1,
});

PaymentSchema.index({
  status: 1,
  expiresAt: 1,
});

const Payment =
  mongoose.models.Payment ||
  mongoose.model<IPayment>("Payment", PaymentSchema);

export default Payment;
